void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    if (hadc->Instance != ADC1) return;


    uint16_t adc_sample = HAL_ADC_GetValue(hadc);
    last_adc_sample = adc_sample;
    new_sample_flag = 1;

    static uint16_t n = 0;
	n++;
	if (n >= 4) {          // 2000/4 = 500 prints/sec
		n = 0;
		print_flag = 1;
	}



    static uint16_t decim_counter = 0;
    const uint16_t K = 2;


    decim_counter++;
    if (decim_counter >= K) {
    	HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
		decim_counter = 0;

		uint16_t mid = 512;
		int16_t delta = (int16_t)sineLookupTable[sin_index] - mid;

		TIM4->CCR4 = mid + delta;
		TIM4->CCR3 = mid - delta;



		sin_index++;
		if (sin_index >= SIN_TAB_LEN) {
			sin_index = 0;
		}
    }
}

